import 'reflect-metadata';
import {test} from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,rmSync} from 'node:fs';
import {join} from 'node:path';
import {tmpdir} from 'node:os';
import {NestFactory} from '@nestjs/core';
import {AppModule} from '../../dist/app.module.js';
import {IdentityService} from '../../dist/modules/identity/identity.service.js';
import {inject} from '../helpers/inject.mjs';
test('HTTP authentication rejects cross-site writes, issues HttpOnly cookies, and revokes logout sessions',async t=>{
 const directory=mkdtempSync(join(tmpdir(),'research-auth-http-'));process.env.DATABASE_PATH=join(directory,'db.sqlite');process.env.APP_ORIGIN='http://app.test';
 const app=await NestFactory.create(AppModule,{logger:false});app.setGlobalPrefix('api/v1');await app.init();t.after(async()=>{await app.close();rmSync(directory,{recursive:true,force:true});delete process.env.DATABASE_PATH;delete process.env.APP_ORIGIN});
 await app.get(IdentityService).createAccount('researcher','research-passphrase-2026');
 assert.equal((await inject(app,{path:'/api/v1/health'})).status,200);
 assert.equal((await inject(app,{path:'/api/v1/ready'})).status,200);
 assert.equal((await inject(app,{path:'/api/v1/me'})).status,401);
 const body={username:'researcher',password:'research-passphrase-2026'};
 assert.equal((await inject(app,{method:'POST',path:'/api/v1/auth/login',headers:{origin:'http://evil.test'},body})).status,403);
 const priorNodeEnv=process.env.NODE_ENV;process.env.NODE_ENV='production';
 const login=await inject(app,{method:'POST',path:'/api/v1/auth/login',headers:{origin:'http://app.test'},body});
 if(priorNodeEnv===undefined)delete process.env.NODE_ENV;else process.env.NODE_ENV=priorNodeEnv;
 assert.equal(login.status,200);assert.match(login.headers['set-cookie'],/; Secure/);assert.match(login.headers['set-cookie'],/HttpOnly/);assert.match(login.headers['set-cookie'],/SameSite=Lax/);
 const cookie=login.headers['set-cookie'].split(';')[0];
 assert.equal((await inject(app,{path:'/api/v1/me',headers:{cookie}})).body.user.username,'researcher');
 assert.equal((await inject(app,{method:'PATCH',path:'/api/v1/me/preferences',headers:{cookie,origin:'http://app.test'},body:{timezone:'Asia/Tokyo'}})).status,403);
 const headers={cookie,origin:'http://app.test','x-csrf-token':login.body.csrfToken};
 assert.equal((await inject(app,{method:'PATCH',path:'/api/v1/me/preferences',headers,body:{timezone:'Asia/Tokyo'}})).status,200);
 assert.equal((await inject(app,{method:'PATCH',path:'/api/v1/me/preferences',headers,body:{userId:'other'}})).status,400);
 assert.equal((await inject(app,{method:'POST',path:'/api/v1/auth/logout',headers})).status,200);
 assert.equal((await inject(app,{path:'/api/v1/me',headers:{cookie}})).status,401);
});
