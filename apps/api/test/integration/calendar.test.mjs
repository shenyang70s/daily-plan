import 'reflect-metadata';
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { mkdtempSync, rmSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { NestFactory } from '@nestjs/core';
import { AppModule } from '../../dist/app.module.js';
import { IdentityService } from '../../dist/modules/identity/identity.service.js';
import { inject } from '../helpers/inject.mjs';

test('calendar writes are owned, versioned, atomic and confirm the current conflicts', async t => {
  const directory = mkdtempSync(join(tmpdir(), 'research-calendar-'));
  const oldDb=process.env.DATABASE_PATH, oldOrigin=process.env.APP_ORIGIN;
  process.env.DATABASE_PATH=join(directory,'db.sqlite');process.env.APP_ORIGIN='http://app.test';
  const app=await NestFactory.create(AppModule,{logger:false});app.setGlobalPrefix('api/v1');await app.init();
  t.after(async()=>{await app.close();rmSync(directory,{recursive:true,force:true});if(oldDb===undefined)delete process.env.DATABASE_PATH;else process.env.DATABASE_PATH=oldDb;if(oldOrigin===undefined)delete process.env.APP_ORIGIN;else process.env.APP_ORIGIN=oldOrigin;});
  const users=[];
  for(const username of ['calendar-owner','calendar-other']){
    await app.get(IdentityService).createAccount(username,'calendar-test-passphrase');
    const login=await inject(app,{method:'POST',path:'/api/v1/auth/login',headers:{origin:'http://app.test'},body:{username,password:'calendar-test-passphrase'}});
    users.push({cookie:login.headers['set-cookie'].split(';')[0],origin:'http://app.test','x-csrf-token':login.body.csrfToken});
  }
  const req=(method,path,body,user=users[0],key=randomUUID())=>inject(app,{method,path:`/api/v1${path}`,headers:{...user,'idempotency-key':key},...(body===undefined?{}:{body})});
  const range={startAt:'2026-10-30T01:00:00Z',endAt:'2026-10-30T02:00:00Z',timezone:'Asia/Shanghai'};
  const query='from=2026-10-29T16:00:00Z&to=2026-10-31T16:00:00Z&timezone=Asia%2FShanghai';
  assert.equal((await inject(app,{path:`/api/v1/calendar?${query}`})).status,401);
  const eventResponse=await req('POST','/calendar/events',{title:'Research meeting',...range,preparationTask:{title:'Prepare slides'}});
  assert.equal(eventResponse.status,201,JSON.stringify(eventResponse.body));
  const event=eventResponse.body;assert.equal(event.preparationTasks.length,1);
  assert.equal((await req('GET',`/tasks/${event.preparationTasks[0].id}`)).body.type,'meeting_prep');
  const task=(await req('POST','/tasks',{title:'Experiment',due:{kind:'date',date:'2026-11-02'}})).body;
  const candidate={taskId:task.id,expectedTaskVersion:task.version,...range};
  const blocked=await req('POST','/schedule-blocks',candidate);
  assert.equal(blocked.status,409);assert.equal(blocked.body.code,'SCHEDULE_CONFLICT');assert.equal(blocked.body.details.conflicts[0].id,event.id);
  assert.equal((await req('GET',`/tasks/${task.id}`)).body.scheduleBlocks.length,0);
  const updatedEvent=(await req('PATCH',`/calendar/events/${event.id}`,{title:'Changed meeting',expectedVersion:event.version})).body;
  const stale=await req('POST','/schedule-blocks',{...candidate,conflictToken:blocked.body.details.confirmationToken});
  assert.equal(stale.status,409);assert.notEqual(stale.body.details.confirmationToken,blocked.body.details.confirmationToken);
  const key=randomUUID();
  const approvedBody={...candidate,conflictToken:stale.body.details.confirmationToken};
  const approved=await req('POST','/schedule-blocks',approvedBody,users[0],key);
  assert.equal(approved.status,201);const block=approved.body;
  assert.equal((await req('POST','/schedule-blocks',approvedBody,users[0],key)).body.id,block.id);
  assert.equal((await req('GET',`/schedule-blocks/${block.id}`,undefined,users[1])).status,404);
  assert.equal((await req('PATCH',`/calendar/events/${event.id}`,{title:'hijack',expectedVersion:updatedEvent.version},users[1])).status,404);
  assert.equal((await req('POST','/calendar/conflicts/check',{...range,exclude:{kind:'event',id:event.id}},users[1])).status,404);
  const otherItems=(await req('GET',`/calendar?${query}`,undefined,users[1])).body.items;assert.deepEqual(otherItems,[]);
  const before=(await req('GET',`/tasks/${task.id}`)).body;
  const moved=await req('PATCH',`/schedule-blocks/${block.id}`,{...range,startAt:'2026-10-30T02:00:00Z',endAt:'2026-10-30T03:00:00Z',expectedVersion:block.version});
  assert.equal(moved.status,200);assert.equal((await req('GET',`/tasks/${task.id}`)).body.due.date,'2026-11-02');
  assert.equal((await req('PATCH',`/schedule-blocks/${block.id}`,{...range,expectedVersion:block.version})).status,409);
  assert.equal((await req('POST','/schedule-blocks',{...candidate,expectedTaskVersion:before.version})).status,409);
  const atomicConflict=await req('POST','/calendar/tasks',{task:{title:'Must not be created on conflict'},schedule:range});
  assert.equal(atomicConflict.status,409);
  assert.equal((await req('GET','/tasks?q=Must%20not%20be%20created')).body.items.length,0);
  const created=await req('POST','/calendar/tasks',{task:{title:'Cross midnight task'},schedule:{...range,startAt:'2026-10-30T15:30:00Z',endAt:'2026-10-30T16:30:00Z'}});
  assert.equal(created.status,201);assert.equal(created.body.task.due,null);assert.equal(created.body.task.status,'todo');assert.equal(created.body.task.scheduleBlocks.length,1);
  assert.equal((await req('GET','/calendar?from=2026-10-30T16:00:00Z&to=2026-10-31T16:00:00Z&timezone=Asia%2FShanghai')).body.items.some(item=>item.resourceId===created.body.block.id),true);
  const current=(await req('GET',`/tasks/${task.id}`)).body;
  const reschedule=await req('POST',`/tasks/${task.id}/reschedule`,{scope:'both',expectedVersion:current.version,due:{kind:'date',date:'2026-11-03'},blocks:[{id:block.id,expectedVersion:moved.body.version,...range,startAt:'2026-10-30T04:00:00Z',endAt:'2026-10-30T05:00:00Z'}]});
  assert.equal(reschedule.status,200);assert.equal(reschedule.body.due.date,'2026-11-03');assert.equal(reschedule.body.scheduleBlocks[0].startAt,'2026-10-30T04:00:00.000Z');
  const blockAfter=(await req('GET',`/schedule-blocks/${block.id}`)).body;
  assert.equal((await req('DELETE',`/schedule-blocks/${block.id}`,{expectedVersion:blockAfter.version})).status,200);
  assert.equal((await req('GET',`/schedule-blocks/${block.id}`)).status,404);
  assert.equal((await req('DELETE',`/calendar/events/${event.id}`,{expectedVersion:updatedEvent.version})).status,200);
  assert.equal((await req('GET',`/tasks/${event.preparationTasks[0].id}`)).status,200);
  assert.equal((await req('POST','/calendar/events',{title:'Reverse',...range,endAt:range.startAt})).status,400);
  assert.equal((await req('GET','/calendar?from=2026-01-01T00:00:00Z&to=2027-01-01T00:00:00Z')).status,400);
});
