import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdtempSync, rmSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { backupDatabase, restoreDatabase } from '../../packages/persistence/dist/backup.js';
import { seedResearchData } from '../demo/research-data.ts';
import { inject } from '../../apps/api/test/helpers/inject.mjs';
const require = createRequire(new URL('../../apps/api/package.json', import.meta.url));
require('reflect-metadata');
const { NestFactory } = require('@nestjs/core');
const { AppModule } = await import('../../apps/api/dist/app.module.js');
const { IdentityService } = await import('../../apps/api/dist/modules/identity/identity.service.js');
const { DatabaseService } = await import('../../apps/api/dist/database.service.js');
test('stop, restore to a new path and restart preserves login, research data and pending reminder state', async t => {
  const directory=mkdtempSync(join(tmpdir(),'research-recovery-drill-')), saved={...process.env}, source=join(directory,'source.sqlite'), backup=join(directory,'backup.sqlite'), restored=join(directory,'restored.sqlite');
  process.env.DATABASE_PATH=source;process.env.APP_ORIGIN='http://recovery.test';delete process.env.DEEPSEEK_API_KEY;delete process.env.PUSH_VAPID_PRIVATE_KEY;
  let app;
  t.after(async()=>{if(app)await app.close();rmSync(directory,{recursive:true,force:true});for(const key of ['DATABASE_PATH','APP_ORIGIN','DEEPSEEK_API_KEY','PUSH_VAPID_PRIVATE_KEY'])if(saved[key]===undefined)delete process.env[key];else process.env[key]=saved[key];});
  const start=async()=>{const value=await NestFactory.create(AppModule,{logger:false});value.setGlobalPrefix('api/v1');await value.init();return value;};
  app=await start();await app.get(IdentityService).createAccount('recovery-user','recovery-test-passphrase');
  let db=app.get(DatabaseService).database;const seeded=seedResearchData(db,'recovery-user');
  const tables=['tasks','projects','calendar_events','task_schedule_blocks','submissions','submission_milestones','reminders','outbox_events','notifications'];
  const before=Object.fromEntries(tables.map(table=>[table,db.all(`SELECT * FROM ${table} WHERE user_id=? ORDER BY id`,seeded.userId)]));
  const migrationsPath=new URL('../../infra/migrations/',import.meta.url).pathname;
  await backupDatabase({source,destination:backup,migrationsPath,revision:'drill'});
  await app.close();app=undefined;
  await restoreDatabase({backup,destination:restored,migrationsPath});process.env.DATABASE_PATH=restored;app=await start();db=app.get(DatabaseService).database;
  assert.equal((await inject(app,{path:'/api/v1/ready'})).status,200);
  const login=await inject(app,{method:'POST',path:'/api/v1/auth/login',headers:{origin:'http://recovery.test'},body:{username:'recovery-user',password:'recovery-test-passphrase'}});
  assert.equal(login.status,200);const headers={cookie:login.headers['set-cookie'].split(';')[0]};
  assert.equal((await inject(app,{path:'/api/v1/submissions',headers})).body.items.length,4);
  assert.equal((await inject(app,{path:'/api/v1/notifications',headers})).body.items.length,3);
  for(const table of tables)assert.deepEqual(db.all(`SELECT * FROM ${table} WHERE user_id=? ORDER BY id`,seeded.userId),before[table],table);
  assert.deepEqual(db.all('PRAGMA foreign_key_check'),[]);
});
